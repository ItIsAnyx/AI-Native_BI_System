// Модели пишут формулы по-разному: \(…\), \[…\], $…$ или $$…$$.
// Приводим всё к $$…$$, которое понимает remark-math. Код (блоки и `inline`) не трогаем.
const CODE = /(```[\s\S]*?(?:```|$)|~~~[\s\S]*?(?:~~~|$)|`[^`\n]*`)/;

function convert(text) {
  return (
    text
      // $$…$$ на отдельной строке — формула-блок (иначе она вышла бы мелкой, «в строке»).
      .replace(/^[ \t]*\$\$([^\n$]+?)\$\$[ \t]*$/gm, (_, body) => `\n$$\n${body.trim()}\n$$\n`)
      // Блок: \[ … \]
      .replace(/\\\[([\s\S]+?)\\\]/g, (_, body) => `\n\n$$\n${body.trim()}\n$$\n\n`)
      // В строке: \( … \)
      .replace(/\\\(([\s\S]+?)\\\)/g, (_, body) => `$$${body.trim()}$$`)
      // В строке: $…$ по правилам Pandoc — после открывающего и перед закрывающим $ нет пробела,
      // за закрывающим не идёт цифра. Так «$5 и $10» остаётся обычным текстом.
      .replace(
        /(?<![\\$])\$(?![\s$])([^$\n]*?[^\s$\\])\$(?![\d$])/g,
        (_, body) => `$$${body}$$`,
      )
  );
}

export function normalizeMath(text) {
  if (typeof text !== "string" || !/[$\\]/.test(text)) return text;
  return text
    .split(CODE)
    .map((part, i) => (i % 2 === 1 ? part : convert(part)))
    .join("");
}
